@Composable
fun ShowScreen(navController:NavController,showId:String,showName:String="") {
    val vm:ShowViewModel=hiltViewModel();val response by vm.episodes.collectAsState();val info by vm.show.collectAsState()
    LaunchedEffect(showId){vm.loadShow(showId)}
    val songs=(response as? Response.Success)?.data.orEmpty();val show=info
    StudioCollection(navController,showName.ifBlank {show?.name ?: "Podcast"},"Episodes",show?.coverUri.orEmpty(),songs,response is Response.Loading)
}
